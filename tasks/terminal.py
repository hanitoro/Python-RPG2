"""Комната 1. Мёртвый терминал.

ЗАДАЧА:
1. Исправить ошибку синтаксиса.
2. access_message(name) должна ВОЗВРАЩАТЬ строку «Доступ: <имя>».
3. boot(name) должна ВОЗВРАЩАТЬ строку «ONLINE | Доступ: <имя>».
4. При вызове boot() ничего не печатать: результат нужен другим программам.

Например: boot("Лира") -> "ONLINE | Доступ: Лира"
Не переименовывай функции; остальные файлы не трогай.
"""


def access_message(name):
    return f"Доступ: {name}"


def boot(name):
    status = "ONLINE"
    return f"{status} | {access_message(name)}"


if __name__ == "__main__":
    print(boot("Лира"))
